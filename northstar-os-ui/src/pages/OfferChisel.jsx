import { useState } from 'react'
import Icon from '../components/Icon.jsx'
import { PageHead, Card } from '../ui.jsx'
import { api } from '../services/api.js'

export default function OfferChisel({ toast }) {
  const [title, setTitle] = useState('')
  const [style, setStyle] = useState('SEO-first')
  const [genTitle, setGenTitle] = useState('')
  const [genBullets, setGenBullets] = useState('')
  const [genKeywords, setGenKeywords] = useState('')
  const [loading, setLoading] = useState(false)
  const [err, setErr] = useState(null)

  const generate = async () => {
    const base = title.trim()
    if (!base) { toast('Enter a product name first', 'err'); return }
    setLoading(true)
    setErr(null)
    try {
      const prompt = `You are OfferChisel, an Amazon listing optimizer. Style: ${style}. Tone: bold, clear, premium, practical, non-cheesy. For the product "${base}", produce exactly three labeled sections:
TITLE: an SEO-optimized Amazon title (max 200 chars).
BULLETS: exactly 4 bullet points, each on its own line starting with "-".
KEYWORDS: comma-separated back-end search terms (8-12 terms).
Do not include any other text. Never mention brands you cannot verify.`
      const res = await api.autothinkRun({ query: prompt, provider: 'local', tier: 'T2' })
      const content = res.content || ''
      const t = content.match(/TITLE:\s*([^\n]+)/i)?.[1]?.trim() || ''
      const b = content.match(/BULLETS:([\s\S]*?)(?=KEYWORDS:)/i)?.[1]?.trim() || ''
      const k = content.match(/KEYWORDS:\s*([^\n]+)/i)?.[1]?.trim() || ''
      setGenTitle(t)
      setGenBullets(b)
      setGenKeywords(k)
      toast(`Generated by ${res.model || 'local engine'} in ${(res.elapsed_ms / 1000).toFixed(1)}s`, 'ok')
    } catch (e) {
      setErr(e.message)
      toast('Generation failed — engine unreachable', 'err')
    } finally {
      setLoading(false)
    }
  }

  return (
    <div className="page">
      <PageHead
        title="OfferChisel"
        sub="Listing Optimizer Agent — real generation via local engine"
        badges={[{ label: 'live · local engine', tone: 'live' }]}
      />

      <div className="stack" style={{ marginTop: 14 }}>
        <Card title="Generate Listing" icon="chisel">
          <div style={{ display: 'flex', flexWrap: 'wrap', gap: 10, alignItems: 'flex-end' }}>
            <input className="field" style={{ flex: 1 }} placeholder="Product name, e.g. Kirkland Signature Whole Bean Coffee 2.5lb" value={title} onChange={(e) => setTitle(e.target.value)} aria-label="Product name" />
            <div className="select-wrap">
              <select className="field" value={style} onChange={(e) => setStyle(e.target.value)} aria-label="Style">
                <option>SEO-first</option>
                <option>Human-first</option>
                <option>A+ rich</option>
              </select>
              <Icon name="caret" size={13} />
            </div>
            <button className="btn btn-primary" onClick={generate} disabled={loading}>
              <Icon name="create" size={15} /> {loading ? 'Generating…' : 'Generate'}
            </button>
          </div>
          {err && <div className="text-coral" style={{ fontSize: 12, marginTop: 8 }}>{err}</div>}
        </Card>

        {(genTitle || genBullets) && (
          <Card title="Generated Output" icon="create">
            <div className="stack">
              {genTitle && (
                <div className="list-row">
                  <div style={{ flex: 1 }}>
                    <div className="text-low" style={{ fontSize: 11 }}>TITLE</div>
                    <div style={{ fontSize: 13, fontWeight: 600 }}>{genTitle}</div>
                  </div>
                  <button className="btn btn-ghost" onClick={() => { navigator.clipboard?.writeText(genTitle); toast('Title copied', 'ok') }}>Copy</button>
                </div>
              )}
              {genBullets && (
                <div className="list-row">
                  <div style={{ flex: 1 }}>
                    <div className="text-low" style={{ fontSize: 11 }}>BULLETS</div>
                    <ul style={{ margin: '4px 0', fontSize: 12.5, paddingLeft: 16, whiteSpace: 'pre-wrap' }}>
                      {genBullets.split('\n').filter((l) => l.trim().replace(/^-\s*/, '')).map((l, i) => <li key={i}>{l.replace(/^-\s*/, '')}</li>)}
                    </ul>
                  </div>
                </div>
              )}
              {genKeywords && (
                <div className="list-row">
                  <div style={{ flex: 1 }}>
                    <div className="text-low" style={{ fontSize: 11 }}>BACK-END KEYWORDS</div>
                    <div style={{ display: 'flex', flexWrap: 'wrap', gap: 6 }}>
                      {genKeywords.split(',').map((k) => k.trim()).filter(Boolean).map((k) => <span key={k} className="badge badge-ok">{k}</span>)}
                    </div>
                  </div>
                </div>
              )}
            </div>
          </Card>
        )}
      </div>
    </div>
  )
}