import { useState } from 'react'
import Icon from '../components/Icon.jsx'
import { PageHead, Card, Metric } from '../ui.jsx'
import { api } from '../services/api.js'

export default function TownCrier({ toast }) {
  const [brief, setBrief] = useState('')
  const [platform, setPlatform] = useState('Meta')
  const [caption, setCaption] = useState('')
  const [tags, setTags] = useState([])
  const [loading, setLoading] = useState(false)
  const [err, setErr] = useState(null)

  const generate = async () => {
    if (!brief.trim()) { toast('Enter a post brief first', 'err'); return }
    setLoading(true)
    setErr(null)
    try {
      const prompt = `You are The Town Crier, social media agent. Brand voice: bold, clear, premium, emotionally honest, practical, non-cheesy. Platform: ${platform}. CRITICAL RULE: Word Coffee is NOT a beverage — never reference coffee beans, k-cups, or drinking the product. Write ONE caption (max 220 chars) for this brief: "${brief}". Then on the next line list 3-4 hashtags separated by spaces. Do not include any other text.`
      const res = await api.autothinkRun({ query: prompt, provider: 'local', tier: 'T2' })
      const content = res.content || ''
      const lines = content.split('\n').map((l) => l.trim()).filter(Boolean)
      const tagIdx = lines.findIndex((l) => l.startsWith('#'))
      if (tagIdx >= 0) {
        setCaption(lines.slice(0, tagIdx).join(' '))
        setTags(lines.slice(tagIdx).flatMap((l) => l.split(/\s+/)).filter((t) => t.startsWith('#')))
      } else {
        setCaption(lines[0] || '')
        setTags([])
      }
      toast(`Generated by ${res.model || 'local engine'} in ${(res.elapsed_ms / 1000).toFixed(1)}s`, 'ok')
    } catch (e) {
      setErr(e.message)
      toast('Generation failed — engine unreachable', 'err')
    } finally {
      setLoading(false)
    }
  }

  const schedule = () => {
    if (!caption) { toast('Generate a caption first', 'err'); return }
    toast(`Scheduled to ${platform} — publish gate closed (requires approval)`, 'ok')
  }

  return (
    <div className="page">
      <PageHead
        title="The Town Crier"
        sub="Social Media Agent — live caption generation via brand voice"
        badges={[{ label: 'live · local engine', tone: 'live' }]}
      />

      <div className="stack" style={{ marginTop: 14 }}>
        <Card title="Brand Voice — Word Coffee" icon="crier">
          <div className="text-mid" style={{ fontSize: 13 }}>bold, clear, premium, emotionally honest, practical, non-cheesy</div>
          <div className="text-low" style={{ fontSize: 12, marginTop: 8 }}>
            Rule enforced: Word Coffee is NOT a beverage. Never reference coffee beans, k-cups, or drinking the product.
          </div>
        </Card>

        <Card title="Content Studio" icon="create">
          <textarea className="field" placeholder="Describe the post — e.g. a calm morning-ritual shot for moms…" value={brief} onChange={(e) => setBrief(e.target.value)} aria-label="Post brief" />
          <div style={{ display: 'flex', flexWrap: 'wrap', gap: 8, marginTop: 8 }}>
            <div className="select-wrap">
              <select className="field" value={platform} onChange={(e) => setPlatform(e.target.value)} style={{ width: 120 }} aria-label="Platform">
                <option>Meta</option>
                <option>Instagram</option>
                <option>TikTok</option>
              </select>
              <Icon name="caret" size={13} />
            </div>
            <button className="btn btn-primary" onClick={generate} disabled={loading}>
              <Icon name="create" size={15} /> {loading ? 'Generating…' : 'Generate caption'}
            </button>
            <button className="btn" onClick={schedule}>Schedule this caption</button>
          </div>
          {err && <div className="text-coral" style={{ fontSize: 12, marginTop: 8 }}>{err}</div>}
        </Card>

        {caption && (
          <Card title="Generated Caption" icon="listings">
            <div className="stack">
              <div className="list-row">
                <div style={{ flex: 1 }}>
                  <div style={{ fontSize: 13.5 }}>"{caption}"</div>
                  {tags.length > 0 && (
                    <div style={{ display: 'flex', flexWrap: 'wrap', gap: 6, marginTop: 8 }}>
                      {tags.map((t) => <span key={t} className="badge badge-ok">{t}</span>)}
                    </div>
                  )}
                </div>
                <button className="btn btn-ghost" onClick={() => { navigator.clipboard?.writeText(caption); toast('Caption copied', 'ok') }}>Copy</button>
              </div>
            </div>
          </Card>
        )}

        <Card title="Snapshot" icon="gauge">
          <div className="metric">
            <Metric k="Channels" v="3" d="Meta / TikTok / IG" />
            <Metric k="Brand Voices" v="1" d="Word Coffee loaded" tone="glow" />
            <Metric k="Publishing" v="GATED" d="requires approval" tone="coral" />
          </div>
        </Card>
      </div>
    </div>
  )
}