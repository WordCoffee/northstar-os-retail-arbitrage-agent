import { useState } from 'react'
import Icon from '../../components/Icon.jsx'
import { PageHead, Card } from '../ui.jsx'
import { api } from '../services/api.js'

const SUGGESTED = [
  'Start a new packaging design from scratch',
  'a face wash on a fresh green background with water drops',
  'Design a lime soda with ice and fresh limes around it',
  'Premium matte black box for a skincare serum',
  'Stand-up pouch for specialty coffee beans',
]

export default function PackifyDesign({ toast }) {
  const [prompt, setPrompt] = useState('')
  const [credits, setCredits] = useState(49)
  const [sessions, setSessions] = useState([])
  const [active, setActive] = useState(null)
  const [loading, setLoading] = useState(false)
  const [err, setErr] = useState(null)
  const [result, setResult] = useState(null)

  const run = async (p) => {
    const base = (p || prompt).trim()
    if (!base) { toast('Enter a design prompt first', 'err'); return }
    if (credits < 10) { toast('Insufficient credits — top up or upgrade', 'err'); return }
    setLoading(true); setErr(null)
    try {
      const res = await api.autothinkRun({ query: `You are Packify, an AI packaging designer. Design a packaging concept for: "${base}". Return a short spec: template, colors (hex), typography, claims (max 3), and a 1-line dieline note.`, provider: 'local', tier: 'T2' })
      const content = res.content || ''
      const sess = { id: Date.now(), prompt: base, content, model: res.model, at: new Date().toLocaleTimeString() }
      setSessions(s => [sess, ...s])
      setActive(sess.id)
      setResult(content)
      setCredits(c => c - 10)
      toast(`Design generated by ${res.model || 'local engine'} — 10 credits`, 'ok')
    } catch (e) {
      setErr(e.message)
      toast('Generation failed — engine unreachable', 'err')
    } finally {
      setLoading(false)
    }
  }

  return (
    <div className="page">
      <PageHead title="Package Design" subtitle="Text → packaging concept, dieline spec, and brand-consistent claims. Packify-style, runs on your own engine." />
      <div style={{ display: 'grid', gridTemplateColumns: '220px 1fr', gap: 16 }}>
        <Card>
          <div style={{ fontWeight: 600, marginBottom: 8 }}>Workspace</div>
          <div style={{ fontSize: 12, opacity: 0.7, marginBottom: 12 }}>Brand kit · Sessions</div>
          <button className="btn" style={{ width: '100%', marginBottom: 12 }} onClick={() => { setResult(null); setPrompt('') }}>+ New project</button>
          <div style={{ fontSize: 12, fontWeight: 600, marginBottom: 6 }}>Sessions</div>
          <div style={{ maxHeight: 260, overflow: 'auto' }}>
            {sessions.length === 0 && <div style={{ fontSize: 12, opacity: 0.5 }}>No sessions yet</div>}
            {sessions.map(s => (
              <div key={s.id} onClick={() => { setActive(s.id); setResult(s.content) }} style={{ padding: '6px 8px', borderRadius: 6, cursor: 'pointer', background: active === s.id ? 'rgba(255,255,255,0.08)' : 'transparent', fontSize: 12, marginBottom: 4 }}>
                {s.prompt.slice(0, 40)}
              </div>
            ))}
          </div>
          <div style={{ marginTop: 16, fontSize: 12, fontWeight: 600 }}>Credits</div>
          <div style={{ fontSize: 20, fontWeight: 700, marginTop: 4 }}>{credits}</div>
          <div style={{ fontSize: 11, opacity: 0.6, marginTop: 2 }}>AI Design = 10 credits</div>
        </Card>
        <div>
          <Card>
            <div style={{ display: 'flex', gap: 8, marginBottom: 12 }}>
              <input value={prompt} onChange={e => setPrompt(e.target.value)} placeholder="What would you like to design?" style={{ flex: 1, padding: '8px 10px', borderRadius: 6, border: '1px solid rgba(255,255,255,0.15)', background: 'transparent', color: 'inherit' }} onKeyDown={e => { if (e.key === 'Enter' && !e.shiftKey) { e.preventDefault(); run() } }} />
              <button className="btn btn-primary" onClick={() => run()} disabled={loading}>{loading ? 'Designing…' : 'Generate'}</button>
            </div>
            <div style={{ display: 'flex', flexWrap: 'wrap', gap: 6, marginBottom: 12 }}>
              {SUGGESTED.map(s => <button key={s} className="btn" style={{ fontSize: 11, padding: '4px 8px' }} onClick={() => { setPrompt(s); run(s) }} disabled={loading}>{s}</button>)}
            </div>
            {err && <div style={{ color: '#ff6b6b', fontSize: 12, marginBottom: 8 }}>{err}</div>}
            {result && (
              <div style={{ whiteSpace: 'pre-wrap', fontSize: 13, lineHeight: 1.5, padding: 12, borderRadius: 8, background: 'rgba(255,255,255,0.04)', border: '1px solid rgba(255,255,255,0.08)' }}>
                {result}
              </div>
            )}
            {!result && !loading && <div style={{ fontSize: 12, opacity: 0.5, padding: 12 }}>Describe a product and I'll propose a packaging concept, color palette, typography, claims, and a dieline spec.</div>}
          </Card>
        </div>
      </div>
    </div>
  )
}
