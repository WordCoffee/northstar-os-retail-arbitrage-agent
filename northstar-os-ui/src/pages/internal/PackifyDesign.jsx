// Package Design — text brief in, packaging concept + dieline note out.
//
// Honesty contract (credit-ledger/v1 §3, C8): the page DISPLAYS the credit
// balance it reads from /api/v1/credits/me and never computes cost logic. It
// used to start at a hardcoded 49 and subtract 10 on every run — a number the
// ledger has never seen. It also printed `e.message` as the entire error state,
// so an operator got "http_500" and no next step. Both are fixed here: the
// balance is read (and re-read after a run), and every failure names an action.

import { useCallback, useEffect, useMemo, useState } from 'react'
import { PageHead, Card } from '../../ui.jsx'
import { signals } from '../../services/signals.js'
import {
  AI_DESIGN_COST,
  affordability,
  describeError,
  meterLine,
  normaliseMeter,
} from '../../lib/creditMeter.js'

const SUGGESTED = [
  'Start a new packaging design from scratch',
  'a face wash on a fresh green background with water drops',
  'Design a lime soda with ice and fresh limes around it',
  'Premium matte black box for a skincare serum',
  'Stand-up pouch for specialty coffee beans',
]

const BRIEF = (base) =>
  `You are Packify, an AI packaging designer. Design a packaging concept for: "${base}". ` +
  'Return a short spec: template, colors (hex), typography, claims (max 3), and a 1-line dieline note.'

export default function PackifyDesign({ toast }) {
  const [prompt, setPrompt] = useState('')
  const [meter, setMeter] = useState(() => normaliseMeter(null))
  const [meterLoading, setMeterLoading] = useState(true)
  const [sessions, setSessions] = useState([])
  const [active, setActive] = useState(null)
  const [loading, setLoading] = useState(false)
  const [failure, setFailure] = useState(null)
  const [result, setResult] = useState(null)

  const loadMeter = useCallback(async () => {
    setMeterLoading(true)
    try {
      setMeter(normaliseMeter(await signals.credits()))
    } catch (e) {
      setMeter({ ...normaliseMeter(null), reason: 'ledger_error' })
    } finally {
      setMeterLoading(false)
    }
  }, [])

  useEffect(() => { loadMeter() }, [loadMeter])

  const verdict = useMemo(() => affordability(meter, AI_DESIGN_COST), [meter])

  const run = async (raw) => {
    const base = (raw || prompt).trim()
    if (!base) {
      setFailure({ tone: 'input', action: 'edit', message: 'Describe the product first — the brief is what the engine designs from.' })
      return
    }
    if (!verdict.ok) {
      setFailure({
        tone: 'credits',
        action: verdict.reason === 'insufficient' ? 'top_up' : 'retry',
        message: verdict.message,
      })
      return
    }
    setLoading(true); setFailure(null)
    try {
      const res = await signals.autothinkRun({ query: BRIEF(base), provider: 'local', tier: 'T2' })
      const content = String(res.content || '')
      if (!content.trim()) {
        throw Object.assign(new Error('empty_completion'), { status: 502 })
      }
      const sess = { id: Date.now(), prompt: base, content, model: res.model, at: new Date().toLocaleTimeString() }
      setSessions((s) => [sess, ...s])
      setActive(sess.id)
      setResult(content)
      toast(`Design generated by ${res.model || 'local engine'}`, 'ok')
      // Re-read the ledger. The balance is never decremented in the browser.
      loadMeter()
    } catch (e) {
      const described = describeError(e)
      setFailure(described)
      toast(described.message, 'err')
    } finally {
      setLoading(false)
    }
  }

  const balanceLabel = meterLoading ? '…' : (meter.ok ? meter.balance : '—')

  return (
    <div className="page">
      <PageHead title="Package Design" subtitle="Text → packaging concept, dieline spec, and brand-consistent claims. Packify-style, runs on your own engine." />
      <div style={{ display: 'grid', gridTemplateColumns: '220px 1fr', gap: 16 }}>
        <Card>
          <div style={{ fontWeight: 600, marginBottom: 8 }}>Workspace</div>
          <div style={{ fontSize: 12, opacity: 0.7, marginBottom: 12 }}>Brand kit · Sessions</div>
          <button type="button" className="btn" style={{ width: '100%', marginBottom: 12 }} onClick={() => { setResult(null); setPrompt(''); setFailure(null) }}>+ New project</button>
          <div style={{ fontSize: 12, fontWeight: 600, marginBottom: 6 }}>Sessions</div>
          <div style={{ maxHeight: 260, overflow: 'auto' }}>
            {sessions.length === 0 && <div style={{ fontSize: 12, opacity: 0.5 }}>No sessions yet</div>}
            {sessions.map((s) => (
              <div key={s.id} onClick={() => { setActive(s.id); setResult(s.content) }} style={{ padding: '6px 8px', borderRadius: 6, cursor: 'pointer', background: active === s.id ? 'rgba(255,255,255,0.08)' : 'transparent', fontSize: 12, marginBottom: 4 }}>
                {s.prompt.slice(0, 40)}
              </div>
            ))}
          </div>
          <div style={{ marginTop: 16, fontSize: 12, fontWeight: 600 }}>Credits</div>
          <div data-testid="packify-balance" style={{ fontSize: 20, fontWeight: 700, marginTop: 4 }}>{balanceLabel}</div>
          <div data-testid="packify-meter-line" style={{ fontSize: 11, opacity: 0.6, marginTop: 2 }}>{meterLine(meter, AI_DESIGN_COST)}</div>
          {!meter.ok && !meterLoading && (
            <button type="button" className="btn" style={{ marginTop: 8, fontSize: 11, padding: '4px 8px' }} onClick={loadMeter}>Retry balance</button>
          )}
        </Card>
        <div>
          <Card>
            <div style={{ display: 'flex', gap: 8, marginBottom: 12 }}>
              <input value={prompt} onChange={(e) => setPrompt(e.target.value)} placeholder="What would you like to design?" style={{ flex: 1, padding: '8px 10px', borderRadius: 6, border: '1px solid rgba(255,255,255,0.15)', background: 'transparent', color: 'inherit' }} onKeyDown={(e) => { if (e.key === 'Enter' && !e.shiftKey) { e.preventDefault(); run() } }} />
              <button type="button" className="btn btn-primary" onClick={() => run()} disabled={loading} title={verdict.ok ? '' : verdict.message}>{loading ? 'Designing…' : 'Generate'}</button>
            </div>
            <div style={{ display: 'flex', flexWrap: 'wrap', gap: 6, marginBottom: 12 }}>
              {SUGGESTED.map((s) => <button type="button" key={s} className="btn" style={{ fontSize: 11, padding: '4px 8px' }} onClick={() => { setPrompt(s); run(s) }} disabled={loading}>{s}</button>)}
            </div>
            {!meterLoading && !verdict.ok && (
              <div style={{ fontSize: 12, opacity: 0.75, marginBottom: 8 }}>{verdict.message}</div>
            )}
            {failure && (
              <div role="alert" data-testid="packify-error" style={{ marginBottom: 12, padding: '10px 12px', borderRadius: 8, border: '1px solid rgba(255,107,107,0.45)', background: 'rgba(255,107,107,0.08)' }}>
                <div style={{ fontSize: 12, lineHeight: 1.5 }}>{failure.message}</div>
                <div style={{ display: 'flex', gap: 8, marginTop: 8 }}>
                  {failure.action === 'retry' && <button type="button" className="btn" style={{ fontSize: 11, padding: '4px 10px' }} onClick={() => { if (failure.tone === 'credits') loadMeter(); else run() }} disabled={loading}>Retry</button>}
                  {failure.action === 'sign_in' && <a className="btn" style={{ fontSize: 11, padding: '4px 10px' }} href="/sign-in">Sign in</a>}
                  {failure.action === 'top_up' && <a className="btn" style={{ fontSize: 11, padding: '4px 10px' }} href="/account">Account &amp; billing</a>}
                  <button type="button" className="btn" style={{ fontSize: 11, padding: '4px 10px' }} onClick={() => setFailure(null)}>Dismiss</button>
                </div>
              </div>
            )}
            {result && (
              <div style={{ whiteSpace: 'pre-wrap', fontSize: 13, lineHeight: 1.5, padding: 12, borderRadius: 8, background: 'rgba(255,255,255,0.04)', border: '1px solid rgba(255,255,255,0.08)' }}>
                {result}
              </div>
            )}
            {!result && !loading && <div style={{ fontSize: 12, opacity: 0.5, padding: 12 }}>Describe a product and I'll propose a packaging concept, color palette, typography, claims, and a dieline spec.</div>}
          </Card>
        </div>
      </div>
    </div>
  )
}
